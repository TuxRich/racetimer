"""The firmware's version for the timer API's hello: `git describe`, as
the WROOM's CMakeLists.txt takes it. A PlatformIO pre-build script:
$BUILD_DIR/generated/version.h. GPL-3.0-or-later."""
import pathlib
import subprocess

Import("env")  # noqa: F821 (SCons)

try:
    version = subprocess.run(["git", "describe", "--tags", "--always", "--dirty"], cwd=env.subst("$PROJECT_DIR"),  # noqa: F821
                             capture_output=True, text=True, check=True).stdout.strip()
except (OSError, subprocess.CalledProcessError):
    version = "unknown"
out = pathlib.Path(env.subst("$BUILD_DIR")) / "generated" / "version.h"  # noqa: F821
text = f'/* Generated by version.py. */\n#pragma once\n#define GATE_VERSION "{version}"\n'
if not out.exists() or out.read_text() != text:  # unchanged: nothing recompiles
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
env.Append(CPPPATH=[str(out.parent)])  # noqa: F821
